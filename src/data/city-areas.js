const sanitizeAreaCities = (cities = []) =>
  cities.filter((city) => ISRAEL_CITIES.includes(city));

export const CITIES_BY_AREA = Object.fromEntries(
  Object.entries(CITY_AREA_MAP).map(([key, cities]) => [
    key,
    sanitizeAreaCities(cities),
  ])
);

export const getCitiesByArea = (area = "") => {
  if (!area) return ISRAEL_CITIES;
  return CITIES_BY_AREA[area] || [];
};
